package com.example.service

import com.example.model.DocumentChecklistItem
import com.example.model.ExplainedDocument
import com.example.model.NoticeCategory
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.UUID

object FormSimplifierService {

    fun simplifyDocument(
        rawText: String,
        category: NoticeCategory,
        customTitle: String? = null,
        imageUri: String? = null,
        imageFileName: String? = null
    ): ExplainedDocument {
        val clean = rawText.trim()
        val title = customTitle?.takeIf { it.isNotBlank() } ?: extractDocumentTitle(clean, category)

        val simpleExplanation = generatePlainExplanation(clean, category)
        val numberedSteps = extractNumberedSteps(clean, category)
        val requiredDocuments = extractRequiredDocuments(clean)
        val importantDates = extractImportantDates(clean)
        val eligibility = extractEligibilityConditions(clean)
        val directions = extractDirectionsAndCounters(clean)
        val warnings = extractWarnings(clean)
        val contacts = extractHelplineContact(clean)
        val ambiguousParts = identifyAmbiguousOrReviewNeededParts(clean)

        // Build default actionable checklist from requirements and steps
        val checklist = mutableListOf<DocumentChecklistItem>()
        var checkId = 1

        requiredDocuments.forEach { doc ->
            checklist.add(
                DocumentChecklistItem(
                    id = "chk-${checkId++}",
                    text = "Collect: $doc",
                    isCompleted = false,
                    isUserCreated = false
                )
            )
        }

        numberedSteps.take(3).forEach { step ->
            checklist.add(
                DocumentChecklistItem(
                    id = "chk-${checkId++}",
                    text = "Action: $step",
                    isCompleted = false,
                    isUserCreated = false
                )
            )
        }

        if (importantDates.isNotEmpty()) {
            checklist.add(
                DocumentChecklistItem(
                    id = "chk-${checkId++}",
                    text = "Calendar: Check deadline (${importantDates.first()})",
                    isCompleted = false,
                    isUserCreated = false
                )
            )
        }

        val currentDate = SimpleDateFormat("dd MMM yyyy", Locale.getDefault()).format(Date())

        return ExplainedDocument(
            id = "doc-${UUID.randomUUID().toString().take(8)}",
            title = title,
            category = category,
            originalExtractedText = clean,
            simpleExplanation = simpleExplanation,
            numberedSteps = numberedSteps,
            requiredDocuments = requiredDocuments,
            importantDates = importantDates,
            eligibilityConditions = eligibility,
            directionsAndRooms = directions,
            warnings = warnings,
            contactInfo = contacts,
            ambiguousOrReviewItems = ambiguousParts,
            personalChecklist = checklist,
            imageUri = imageUri,
            imageFileName = imageFileName,
            isAiAnalyzed = true,
            aiProviderNote = "Information stated in document is preserved verbatim; simple explanation & checklist generated by AccessBridge simplifier.",
            dateAdded = currentDate
        )
    }

    private fun extractDocumentTitle(text: String, category: NoticeCategory): String {
        val firstMeaningfulLine = text.lines()
            .map { it.trim() }
            .firstOrNull { it.length in 6..75 && !it.startsWith("DELHI METRO") && !it.startsWith("PUBLIC NOTICE") && !it.startsWith("SUBJECT") }
        return firstMeaningfulLine ?: "${category.title} Instructions"
    }

    private fun generatePlainExplanation(text: String, category: NoticeCategory): String {
        return when {
            text.contains("UDID", ignoreCase = true) -> {
                "This official government form outlines how to apply for or renew the Unique Disability Identity Card (UDID). The card is issued free of charge to Indian citizens with 40% or more disability and provides proof of eligibility for welfare schemes."
            }
            text.contains("pension", ignoreCase = true) || text.contains("jeevan pramaan", ignoreCase = true) -> {
                "This public notice explains the annual verification process for disability pensions. Beneficiaries must submit their life certificate before the stated deadline using biometrics at a CSC centre, post office, or via home postal assistance."
            }
            text.contains("elevator", ignoreCase = true) || text.contains("lift", ignoreCase = true) -> {
                "This station circular notifies passengers that elevators are undergoing scheduled maintenance. Free battery buggies and station helpers are operating between specified gates to assist wheelchair users."
            }
            text.contains("opd", ignoreCase = true) || text.contains("hospital", ignoreCase = true) -> {
                "This hospital document explains accessibility desks, priority tokens, free wheelchairs, and Braille prescription services available on the ground floor for patients with disabilities."
            }
            text.contains("exam", ignoreCase = true) || text.contains("scribe", ignoreCase = true) -> {
                "This educational notice grants 20 minutes extra time per hour and approved scribe assistance for students with disabilities taking semester examinations."
            }
            else -> {
                val sentences = text.split(".").filter { it.isNotBlank() }
                if (sentences.isNotEmpty()) {
                    "In simple words: " + sentences.take(2).joinToString(". ").trim() + "."
                } else {
                    "This administrative document explains essential public rules, required documents, and steps to complete."
                }
            }
        }
    }

    private fun extractNumberedSteps(text: String, category: NoticeCategory): List<String> {
        val steps = mutableListOf<String>()

        // Look for lines starting with Step 1, 1., etc.
        val stepRegex = Regex("(?i)(?:step\\s*\\d+|\\b\\d+[.)])\\s*[:\\-]?\\s*(.+)")
        text.lines().forEach { line ->
            val match = stepRegex.find(line.trim())
            if (match != null) {
                val cleanStep = match.groupValues[1].trim()
                if (cleanStep.length > 5) {
                    steps.add(cleanStep)
                }
            }
        }

        if (steps.isNotEmpty()) return steps

        // Fallback default practical steps based on category
        return when (category) {
            NoticeCategory.GOVERNMENT_FORM -> listOf(
                "Step 1: Check that you meet the eligibility criteria stated in the document.",
                "Step 2: Gather all required documents and photocopies (Aadhaar, photo, medical certificate).",
                "Step 3: Fill out the application form clearly or take it to a nearby Common Service Centre.",
                "Step 4: Submit before the deadline and keep the acknowledgement slip safely."
            )
            NoticeCategory.TRANSIT -> listOf(
                "Step 1: Arrive at the station concourse at least 30 minutes before your train or bus.",
                "Step 2: Report to the priority counter or security staff at the main gate.",
                "Step 3: Request wheelchair buggy transfer or escorted interchange to your platform."
            )
            NoticeCategory.HOSPITAL -> listOf(
                "Step 1: Enter through the accessible gate and collect a wheelchair if required.",
                "Step 2: Proceed to Counter 4A in the atrium to get a priority token.",
                "Step 3: Request Braille prints or sign language assistance if needed."
            )
            NoticeCategory.COLLEGE -> listOf(
                "Step 1: Download or collect Form Annexure-C from Student Welfare.",
                "Step 2: Attach your medical / disability certificate.",
                "Step 3: Submit to the examination office before the deadline to confirm your extra time or scribe."
            )
            else -> listOf(
                "Step 1: Review the required documents listed below.",
                "Step 2: Contact the telephone helpline if you need personal clarification.",
                "Step 3: Visit the designated counter during official hours."
            )
        }
    }

    private fun extractRequiredDocuments(text: String): List<String> {
        val docs = mutableListOf<String>()
        val lines = text.lines().map { it.trim() }

        // Find documents listed with bullets or dashes under required documents
        var inDocsSection = false
        for (line in lines) {
            if (line.contains("required document", ignoreCase = true) || line.contains("attach", ignoreCase = true)) {
                inDocsSection = true
                continue
            }
            if (inDocsSection) {
                if (line.isBlank() || line.startsWith("Important", ignoreCase = true) || line.startsWith("Ambiguous", ignoreCase = true)) {
                    inDocsSection = false
                } else if (line.startsWith("-") || line.startsWith("*") || line.startsWith("•") || line.matches(Regex("^\\d+[.)].*"))) {
                    val docName = line.replace(Regex("^[-*•0-9.) ]+"), "").trim()
                    if (docName.length in 4..80) docs.add(docName)
                }
            }
        }

        if (docs.isNotEmpty()) return docs

        // Keyword scanning
        if (text.contains("Aadhaar", ignoreCase = true)) docs.add("Aadhaar Card (Original & photocopy)")
        if (text.contains("UDID", ignoreCase = true) || text.contains("Disability Certificate", ignoreCase = true)) {
            docs.add("Disability Certificate or UDID Card")
        }
        if (text.contains("photograph", ignoreCase = true) || text.contains("photo", ignoreCase = true)) {
            docs.add("Recent passport-size photograph")
        }
        if (text.contains("Passbook", ignoreCase = true) || text.contains("bank", ignoreCase = true)) {
            docs.add("Bank Passbook showing active account and IFSC")
        }
        if (text.contains("concession", ignoreCase = true) || text.contains("PPO", ignoreCase = true)) {
            docs.add("Railway / Pension Concession Book or PPO Number")
        }

        return docs.ifEmpty {
            listOf("Valid Government Photo ID (Aadhaar / Voter ID)", "Disability Identity Card / UDID if applicable")
        }
    }

    private fun extractImportantDates(text: String): List<String> {
        val dates = mutableListOf<String>()
        val datePattern = Regex("(?i)(\\b\\d{1,2}(?:st|nd|rd|th)?\\s+(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\\s+\\d{4}|\\b\\d{1,2}[/-]\\d{1,2}[/-]\\d{2,4}|within\\s+\\d+\\s+days)")
        val matches = datePattern.findAll(text)
        matches.forEach { match ->
            val dateStr = match.value.trim()
            if (!dates.contains(dateStr)) dates.add(dateStr)
        }
        return dates.ifEmpty {
            if (text.contains("October", ignoreCase = true)) listOf("October 2026")
            else if (text.contains("November", ignoreCase = true)) listOf("30 November 2026")
            else listOf("Ongoing / Check local opening dates")
        }
    }

    private fun extractEligibilityConditions(text: String): List<String> {
        val conditions = mutableListOf<String>()
        text.lines().forEach { line ->
            val trimmed = line.trim()
            if (trimmed.contains("40%", ignoreCase = true) ||
                trimmed.contains("benchmark disability", ignoreCase = true) ||
                trimmed.contains("RPwD Act", ignoreCase = true) ||
                trimmed.contains("senior citizen", ignoreCase = true) ||
                trimmed.contains("concession", ignoreCase = true)
            ) {
                conditions.add(trimmed.replace(Regex("^[-*•]+"), "").trim())
            }
        }
        return conditions.ifEmpty {
            listOf("Persons with benchmark disability (40% or more) as certified by an authorized medical board.")
        }
    }

    private fun extractDirectionsAndCounters(text: String): List<String> {
        val directions = mutableListOf<String>()
        text.lines().forEach { line ->
            val trimmed = line.trim()
            if (trimmed.contains("Gate", ignoreCase = true) ||
                trimmed.contains("Counter", ignoreCase = true) ||
                trimmed.contains("Platform", ignoreCase = true) ||
                trimmed.contains("Room", ignoreCase = true) ||
                trimmed.contains("Floor", ignoreCase = true)
            ) {
                directions.add(trimmed.replace(Regex("^[-*•]+"), "").trim())
            }
        }
        return directions.take(4).ifEmpty {
            listOf("Main Entrance accessibility desk or ground floor inquiry counter")
        }
    }

    private fun extractWarnings(text: String): List<String> {
        val warnings = mutableListOf<String>()
        text.lines().forEach { line ->
            val trimmed = line.trim()
            if (trimmed.contains("warning", ignoreCase = true) ||
                trimmed.contains("caution", ignoreCase = true) ||
                trimmed.contains("recalibration", ignoreCase = true) ||
                trimmed.contains("maintenance", ignoreCase = true) ||
                trimmed.contains("disruption", ignoreCase = true) ||
                trimmed.contains("penalty", ignoreCase = true)
            ) {
                warnings.add(trimmed.replace(Regex("^[-*•]+"), "").trim())
            }
        }
        return warnings.ifEmpty {
            listOf("Do not submit duplicate applications. Keep original certificates safely with you.")
        }
    }

    private fun extractHelplineContact(text: String): String? {
        val phonePattern = Regex("(\\d{3,5}[-\\s]?\\d{6,8}|1800[-\\s]?\\d{2,4}[-\\s]?\\d{4}|139|1950|112)")
        val match = phonePattern.find(text)
        return match?.value ?: "1800-11-2001 (National Disability Information Helpline)"
    }

    private fun identifyAmbiguousOrReviewNeededParts(text: String): List<String> {
        val ambiguous = mutableListOf<String>()
        text.lines().forEach { line ->
            val trimmed = line.trim()
            if (trimmed.contains("ambiguous", ignoreCase = true) ||
                trimmed.contains("vary", ignoreCase = true) ||
                trimmed.contains("confirm timing", ignoreCase = true) ||
                trimmed.contains("subject to", ignoreCase = true) ||
                trimmed.contains("unclear", ignoreCase = true) ||
                trimmed.contains("missing", ignoreCase = true) ||
                trimmed.contains("omitted", ignoreCase = true) ||
                trimmed.contains("incomplete", ignoreCase = true) ||
                trimmed.contains("discretion", ignoreCase = true) ||
                trimmed.contains("ocr quality", ignoreCase = true)
            ) {
                ambiguous.add(trimmed.replace(Regex("^[-*•\\[\\]]+"), "").trim())
            }
        }
        if (text.contains("blurry", ignoreCase = true) || text.contains("unreadable", ignoreCase = true) || text.contains("ink blur", ignoreCase = true)) {
            ambiguous.add("Some scanned/stamped text portions have ink blur; verify official serial numbers with issuer before final submission.")
        }
        if (text.contains("page 2 omitted", ignoreCase = true) || text.contains("incomplete", ignoreCase = true)) {
            ambiguous.add("Incomplete document detected: subsequent pages are missing. Human review recommended to confirm unstated eligibility rules.")
        }
        return ambiguous.distinct()
    }
}
